  function renderTableList() {
    const searchTerm = els.search.value.toLowerCase();
    const container = els.tablesList;
    container.innerHTML = "";

    function appendItem(kind, id, title, info) {
      const div = document.createElement("div");
      div.className = `table-item kind-${kind}`;
      if (selected && selected.kind === kind && selected.id === id) div.classList.add("active");
      div.innerHTML = `<div class="table-name">${escapeHtml(title)}</div><div class="table-info">${escapeHtml(info)}</div>`;
      div.addEventListener("click", () => {
        selectObject(kind, id);
        const prefix = { table: "table", view: "view", trigger: "trigger" }[kind];
        const card = document.getElementById(`${prefix}-${id}`);
        if (card) card.scrollIntoView({ behavior: "smooth", block: "center" });
      });
      container.appendChild(div);
    }

    Object.values(tables).forEach((table) => {
      if (searchTerm && !table.name.toLowerCase().includes(searchTerm)) return;
      appendItem("table", table.id, table.name, `${Object.keys(table.columns).length} colunas`);
    });

    Object.values(views).forEach((view) => {
      if (searchTerm && !view.name.toLowerCase().includes(searchTerm)) return;
      let modeLabel;
      if (view.mode === "sql") {
        modeLabel = "SQL customizado";
      } else {
        modeLabel = "Visual";
      }
      appendItem("view", view.id, view.name, `View | ${modeLabel}`);
    });

    triggers.forEach((trg) => {
      if (searchTerm && !trg.name.toLowerCase().includes(searchTerm)) return;
      appendItem("trigger", trg.id, trg.name, `Trigger | ${trg.timing} ${(trg.events || []).join("/")}`);
    });
  }

