  function importSQL() {
    const sql = prompt(`Cole o SQL para importar (formato ${dbConfig[currentDatabase].name}):`);
    if (!sql) return;
    const tableRegex = /CREATE\s+TABLE\s+`?(\w+)`?\s*\(([^;]+)\)/gi;
    let match;
    let imported = 0;
    while ((match = tableRegex.exec(sql)) !== null) {
      const tableName = match[1];
      const columnsDef = match[2];
      let engine = "InnoDB", charset = "utf8mb4", collation = "utf8mb4_unicode_ci", tableComment = "";
      const engineMatch = columnsDef.match(/ENGINE\s*=\s*(\w+)/i);
      if (engineMatch) engine = engineMatch[1];
      const charsetMatch = columnsDef.match(/CHARSET\s*=\s*(\w+)/i);
      if (charsetMatch) charset = charsetMatch[1];
      const commentMatch = columnsDef.match(/COMMENT\s*=\s*['"]([^'"]+)['"]/i);
      if (commentMatch) tableComment = commentMatch[1];
      const existing = Object.values(tables).find((t) => t.name === tableName);
      if (existing && !confirm(`Tabela "${tableName}" ja existe. Substituir?`)) continue;
      if (existing) {
        delete tables[existing.id];
        foreignKeys = foreignKeys.filter((fk) => fk.sourceTableId !== existing.id && fk.targetTableId !== existing.id);
        indexes = indexes.filter((idx) => idx.tableId !== existing.id);
        triggers = triggers.filter((t) => t.tableId !== existing.id);
      }
      const tableId = nextTableId++;
      const table = new Table(tableId, tableName, 100, 100, tableComment, engine, charset, collation);
      const columnLines = columnsDef.split(",");
      let hasPK = false;
      columnLines.forEach((line) => {
        line = line.trim();
        if (line.toUpperCase().startsWith("PRIMARY KEY")) return;
        const colMatch = line.match(/`?(\w+)`?\s+(\w+)(?:\(([^)]+)\))?(?:\s+NOT\s+NULL)?(?:\s+AUTO_INCREMENT)?/i);
        if (colMatch) {
          const colId = nextColumnId++;
          const colName = colMatch[1];
          const colType = colMatch[2].toUpperCase();
          const colSize = colMatch[3] || "";
          const notNull = line.toUpperCase().includes("NOT NULL");
          const autoInc = line.toUpperCase().includes("AUTO_INCREMENT");
          const isPK = line.toUpperCase().includes("PRIMARY KEY");
          if (isPK) hasPK = true;
          table.addColumn(new Column(colId, colName, colType, colSize, isPK, notNull, autoInc, "", ""));
          imported++;
        }
      });
      if (!hasPK) {
        table.addColumn(new Column(nextColumnId++, "id", "INT", "", true, true, true, "", "ID"));
      }
      tables[tableId] = table;
    }
    if (imported > 0) {
      afterModelChange({ rerenderPanel: true });
      updateStatus(`${imported} colunas importadas`);
    } else {
      updateStatus("Nenhuma tabela valida encontrada");
    }
  }

