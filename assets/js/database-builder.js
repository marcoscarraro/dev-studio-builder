  class Column {
    constructor(id, name, type, size, isPK, isNotNull, isAI, defaultValue, comment) {
      this.id = id; this.name = name; this.type = type; this.size = size;
      this.isPK = isPK; this.isNotNull = isNotNull; this.isAI = isAI;
      this.defaultValue = defaultValue; this.comment = comment || "";
      this.isFK = false; this.fkRef = null;
    }

    getSQLType() {
      if (this.size && (this.type === "VARCHAR" || this.type === "VARCHAR2" || this.type === "NVARCHAR" || this.type === "DECIMAL" || this.type === "NUMERIC" || this.type === "NUMBER")) {
        return `${this.type}(${this.size})`;
      }
      return this.type;
    }

    toSQL() {
      const config = dbConfig[currentDatabase];
      const q = config.quotes;
      let sql = `${q}${this.name}${q} ${this.getSQLType()}`;
      if (this.isNotNull) sql += ` NOT NULL`;
      if (this.defaultValue && this.defaultValue.trim()) {
        const val = this.defaultValue;
        if (currentDatabase === "mysql" && val === "CURRENT_TIMESTAMP") sql += ` DEFAULT CURRENT_TIMESTAMP`;
        else if (val.match(/^[0-9]+$/) || val === "NULL" || val === "CURRENT_TIMESTAMP") sql += ` DEFAULT ${val}`;
        else sql += ` DEFAULT '${val}'`;
      }
      if (this.isAI && config.autoIncrement) {
        if (currentDatabase === "sqlite") sql += ` PRIMARY KEY AUTOINCREMENT`;
        else sql += ` ${config.autoIncrement}`;
      }
      return sql;
    }
  }

  class Table {
    constructor(id, name, x, y, comment, engine, charset, collation) {
      this.id = id; this.name = name; this.x = x; this.y = y;
      this.columns = {}; this.comment = comment || "";
      this.engine = engine || "InnoDB"; this.charset = charset || "utf8mb4";
      this.collation = collation || "utf8mb4_unicode_ci"; this.width = 320;
    }

    addColumn(column) { this.columns[column.id] = column; }

    toSQL() {
      const config = dbConfig[currentDatabase];
      const q = config.quotes;
      let sql = `CREATE TABLE ${q}${this.name}${q} (\n`;
      const cols = Object.values(this.columns);
      const pkCols = cols.filter((c) => c.isPK && !c.isAI);

      cols.forEach((col, idx) => {
        sql += `  ${col.toSQL()}`;
        if (idx < cols.length - 1 || pkCols.length > 0) sql += `,`;
        sql += `\n`;
      });
      if (pkCols.length > 0) sql += `  PRIMARY KEY (${pkCols.map((c) => `${q}${c.name}${q}`).join(", ")}),\n`;

      const tableIndexes = indexes.filter((idx) => idx.tableId === this.id);
      tableIndexes.forEach((idx) => {
        const idxColumns = idx.columns.map((colId) => `${q}${this.columns[colId]?.name}${q}`).join(", ");
        if (idxColumns) sql += `  ${idx.type} ${q}${idx.name || `${idx.type}_${idxColumns.replace(/`/g, "")}`}${q} (${idxColumns}),\n`;
      });

      if (config.supportsFK) {
        const fks = foreignKeys.filter((fk) => fk.sourceTableId === this.id);
        fks.forEach((fk) => {
          const target = tables[fk.targetTableId];
          const sourceCol = this.columns[fk.sourceColumnId];
          const targetCol = target?.columns[fk.targetColumnId];
          if (sourceCol && targetCol) {
            const fkName = fk.name || `fk_${this.name}_${target.name}`;
            sql += `  CONSTRAINT ${q}${fkName}${q} FOREIGN KEY (${q}${sourceCol.name}${q}) REFERENCES ${q}${target.name}${q}(${q}${targetCol.name}${q})`;
            if (fk.onDelete && config.fkActions) sql += ` ON DELETE ${fk.onDelete}`;
            if (fk.onUpdate && config.fkActions) sql += ` ON UPDATE ${fk.onUpdate}`;
            sql += `,\n`;
          }
        });
      }

      sql = sql.replace(/,\n$/, "\n") + `)`;
      if (currentDatabase === "mysql") {
        sql += ` ENGINE=${this.engine} DEFAULT CHARSET=${this.charset}`;
        if (this.collation) sql += ` COLLATE=${this.collation}`;
        if (this.comment) sql += ` COMMENT = '${this.comment.replace(/'/g, "\\'")}'`;
      }
      sql += `;\n`;
      return sql;
    }

    render() {
      const div = document.createElement("div");
      div.className = "table-card";
      if (selected && selected.kind === "table" && selected.id === this.id) div.classList.add("selected");
      div.id = `table-${this.id}`;
      div.style.left = `${this.x}px`;
      div.style.top = `${this.y}px`;
      const columnsHtml = Object.values(this.columns).map((col) => {
        let flag = '<span class="column-flag flag-empty"></span>';
        if (col.isPK) flag = '<span class="column-flag flag-pk">PK</span>';
        else if (col.isFK) flag = '<span class="column-flag flag-fk">FK</span>';
        return `
          <div class="column-item">
            ${flag}
            <div class="column-name">${escapeHtml(col.name)}</div>
            <div class="column-type">${escapeHtml(col.getSQLType())}</div>
          </div>`;
      }).join("");
      div.innerHTML = `
        <div class="table-header">
          <span class="table-name">${escapeHtml(this.name)}</span>
          <span class="card-kind-badge kind-table">Tabela</span>
        </div>
        <div class="table-columns">${columnsHtml}</div>`;
      div.addEventListener("mousedown", (e) => {
        selectObject("table", this.id, { fromCanvas: true });
        draggingTable = this.id;
        dragStartX = e.clientX - this.x;
        dragStartY = e.clientY - this.y;
        div.classList.add("dragging");
      });
      return div;
    }

    updatePosition(x, y) {
      this.x = x;
      this.y = y;
      const card = document.getElementById(`table-${this.id}`);
      if (card) {
        card.style.left = `${x}px`;
        card.style.top = `${y}px`;
      }
    }
  }

