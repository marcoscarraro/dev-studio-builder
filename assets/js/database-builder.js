  function highlightSQL(code) {
    const parts = [];
    const regex = /('(?:[^'\\]|\\.)*'|"(?:[^"\\]|\\.)*")|(\b\d+(?:\.\d+)?\b)|([A-Za-z_]\w*)/g;
    let lastIndex = 0;
    let m;
    while ((m = regex.exec(code)) !== null) {
      if (m.index > lastIndex) parts.push(escapeHtml(code.slice(lastIndex, m.index)));
      if (m[1]) parts.push(`<span class="tok-str">${escapeHtml(m[1])}</span>`);
      else if (m[2]) parts.push(`<span class="tok-num">${escapeHtml(m[2])}</span>`);
      else if (m[3]) {
        const word = m[3];
        if (SQL_KEYWORDS.includes(word.toUpperCase())) parts.push(`<span class="tok-kw">${escapeHtml(word)}</span>`);
        else parts.push(escapeHtml(word));
      }
      lastIndex = regex.lastIndex;
    }
    if (lastIndex < code.length) parts.push(escapeHtml(code.slice(lastIndex)));
    return parts.join("");
  }

