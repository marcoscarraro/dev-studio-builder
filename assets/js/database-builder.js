  function buildTemplateBody(key, trg) {
    let tableName = "tabela";
    if (trg && tables[trg.tableId]) tableName = tables[trg.tableId].name;
    switch (key) {
      case "audit": return `INSERT INTO audit_log (tabela, operacao, registro_id, data_hora) VALUES ('${tableName}', 'INSERT', NEW.id, NOW());`;
      case "timestamp": return `SET NEW.updated_at = NOW();`;
      case "validate": return `IF NEW.email IS NULL OR NEW.email = '' THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Email invalido'; END IF;`;
      case "stock": return `UPDATE produtos SET estoque = estoque - NEW.quantidade WHERE id = NEW.produto_id;`;
      case "prevent": return `SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Exclusao nao permitida!';`;
      default: return "";
    }
  }

