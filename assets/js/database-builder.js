  // Liga o highlight dos editores de codigo do painel (pre sobreposto ao textarea).
  function wireCodeEditors() {
    els.form.querySelectorAll(".code-editor-wrap").forEach((wrap) => {
      const textarea = wrap.querySelector("textarea");
      const code = wrap.querySelector("pre code");
      const pre = wrap.querySelector("pre");
      if (!textarea || !code || textarea.dataset.wired) return;
      textarea.dataset.wired = "1";
      textarea.addEventListener("input", () => { code.innerHTML = highlightSQL(textarea.value); });
      textarea.addEventListener("scroll", () => { pre.scrollTop = textarea.scrollTop; pre.scrollLeft = textarea.scrollLeft; });
      textarea.addEventListener("keydown", (e) => {
        if (e.key === "Tab") {
          e.preventDefault();
          const s = textarea.selectionStart;
          textarea.value = textarea.value.slice(0, s) + "    " + textarea.value.slice(s);
          textarea.selectionStart = s + 4;
          textarea.selectionEnd = s + 4;
          textarea.dispatchEvent(new Event("input", { bubbles: true }));
        }
      });
    });
  }

