  function handlePanelInput(event) {
    const field = event.target.closest("[data-db-bind]");
    if (!field) return;
    const bind = field.dataset.dbBind;
    const object = getSelectedObject();
    if (!object) return;

    // Re-renderiza o painel apos selects/checkboxes ESTRUTURAIS (mudam outros campos).
    // Inputs de texto nunca re-renderizam o painel (nao perder o foco ao digitar).
    let rerenderPanel = false;

    if (selected.kind === "table") {
      const table = object;
      if (bind === "tableName") table.name = field.value;
      if (bind === "tableEngine") table.engine = field.value;
      if (bind === "tableCharset") table.charset = field.value;
      if (bind === "tableCollation") table.collation = field.value;
      if (bind === "tableComment") table.comment = field.value;

      const colId = parseInt(field.dataset.colId, 10);
      const col = table.columns[colId];
      if (col) {
        if (bind === "colName") col.name = field.value;
        if (bind === "colType") col.type = field.value;
        if (bind === "colSize") col.size = field.value;
        if (bind === "colPK") col.isPK = field.checked;
        if (bind === "colNN") col.isNotNull = field.checked;
        if (bind === "colAI") {
          if (field.checked && Object.values(table.columns).some((c) => c.isAI && c.id !== col.id) && currentDatabase !== "sqlite") {
            field.checked = false;
            updateStatus("Apenas uma coluna pode ter AUTO_INCREMENT");
            return;
          }
          col.isAI = field.checked;
        }
        if (bind === "colDefault") col.defaultValue = field.value;
        if (bind === "colComment") col.comment = field.value;
      }

      const idxId = parseInt(field.dataset.idxId, 10);
      const idx = indexes.find((i) => i.id === idxId);
      if (idx) {
        if (bind === "idxName") idx.name = field.value;
        if (bind === "idxType") idx.type = field.value;
        if (bind === "idxCol") {
          const value = parseInt(field.value, 10);
          if (field.checked) {
            if (!idx.columns.includes(value)) idx.columns.push(value);
          } else {
            idx.columns = idx.columns.filter((c) => c !== value);
          }
        }
      }

      const fkId = parseInt(field.dataset.fkId, 10);
      const fk = foreignKeys.find((f) => f.id === fkId);
      if (fk) {
        if (bind === "fkSourceCol") {
          const oldCol = table.columns[fk.sourceColumnId];
          if (oldCol) oldCol.isFK = false;
          fk.sourceColumnId = parseInt(field.value, 10);
          const newCol = table.columns[fk.sourceColumnId];
          if (newCol) newCol.isFK = true;
        }
        if (bind === "fkTargetTable") {
          fk.targetTableId = parseInt(field.value, 10) || null;
          fk.targetColumnId = null;
          rerenderPanel = true; // repopula o select de coluna destino
        }
        if (bind === "fkTargetCol") fk.targetColumnId = parseInt(field.value, 10) || null;
        if (bind === "fkName") fk.name = field.value;
        if (bind === "fkOnDelete") fk.onDelete = field.value;
        if (bind === "fkOnUpdate") fk.onUpdate = field.value;
      }
    }

    if (selected.kind === "view") {
      const view = object;
      if (bind === "viewName") view.name = field.value;
      if (bind === "viewMode") {
        view.mode = field.value;
        rerenderPanel = true; // alterna construtor visual <-> SQL
      }
      if (bind === "viewSql") view.sql = field.value;
      if (bind === "viewWhere") view.where = field.value;
      if (bind === "viewOrderBy") view.orderBy = field.value;
      if (bind === "viewLimit") view.limit = field.value;
      if (bind === "viewComment") view.comment = field.value;
      if (bind === "viewSourceTables") {
        view.sourceTables = Array.from(field.selectedOptions).map((opt) => opt.value);
        view.selectedColumns = view.selectedColumns.filter((c) => view.sourceTables.includes(c.table));
        rerenderPanel = true; // refaz o seletor de colunas
      }
      if (bind === "viewColCheck") {
        const tableName = field.dataset.table;
        const columnName = field.dataset.column;
        if (field.checked) {
          view.selectedColumns.push({ table: tableName, column: columnName, alias: "" });
        } else {
          view.selectedColumns = view.selectedColumns.filter((c) => !(c.table === tableName && c.column === columnName));
        }
      }
      if (bind === "viewColAlias") {
        const entry = view.selectedColumns.find((c) => c.table === field.dataset.table && c.column === field.dataset.column);
        if (entry) entry.alias = field.value;
      }
    }

    // Campos de trigger (tanto no painel da tabela quanto na trigger avulsa).
    const trgId = parseInt(field.dataset.trgId, 10);
    const trg = triggers.find((t) => t.id === trgId);
    if (trg) {
      if (bind === "trgName") trg.name = field.value;
      if (bind === "trgTable") trg.tableId = parseInt(field.value, 10);
      if (bind === "trgTiming") trg.timing = field.value;
      if (bind === "trgEvent") {
        const value = field.value;
        trg.events = trg.events || [];
        if (field.checked) {
          if (!trg.events.includes(value)) trg.events.push(value);
        } else {
          trg.events = trg.events.filter((evt) => evt !== value);
        }
      }
      if (bind === "trgCode") trg.body = field.value;
      if (bind === "trgDesc") trg.description = field.value;
    }

    afterModelChange({ rerenderPanel });
  }

  function handlePanelClick(event) {
    const actionEl = event.target.closest("[data-db-action]");
    if (!actionEl) return;
    const action = actionEl.dataset.dbAction;
    const object = getSelectedObject();

    if (action === "toggleItem") {
      // Clique no X de remover nao deve expandir/recolher.
      if (event.target.closest(".db-item-remove")) return;
      const kindKey = actionEl.dataset.kind;
      const id = parseInt(actionEl.dataset.id, 10);
      if (expanded[kindKey].has(id)) {
        expanded[kindKey].delete(id);
      } else {
        expanded[kindKey].add(id);
      }
      renderProps();
      return;
    }

    if (action === "removeItem") {
      const kindKey = actionEl.dataset.kind;
      const id = parseInt(actionEl.dataset.id, 10);
      removePanelItem(kindKey, id);
      return;
    }

    if (action === "addColumn" && selected && selected.kind === "table") {
      const table = object;
      const id = nextColumnId++;
      const firstType = typeMappings[currentDatabase][0].value;
      table.addColumn(new Column(id, `coluna_${id}`, firstType, "", false, false, false, "", ""));
      expanded.col.add(id);
      afterModelChange({ rerenderPanel: true });
      updateStatus("Coluna adicionada");
      return;
    }

    if (action === "addIndex" && selected && selected.kind === "table") {
      const id = nextIndexId++;
      indexes.push({ id, name: "", type: "INDEX", tableId: object.id, columns: [] });
      expanded.idx.add(id);
      afterModelChange({ rerenderPanel: true });
      updateStatus("Indice adicionado — marque as colunas");
      return;
    }

    if (action === "addFk" && selected && selected.kind === "table") {
      const table = object;
      const firstCol = Object.values(table.columns)[0];
      if (!firstCol) {
        updateStatus("Adicione colunas antes de criar uma FK");
        return;
      }
      const id = nextFkId++;
      foreignKeys.push({ id, name: "", sourceTableId: table.id, sourceColumnId: firstCol.id, targetTableId: null, targetColumnId: null, onDelete: "", onUpdate: "" });
      expanded.fk.add(id);
      afterModelChange({ rerenderPanel: true });
      updateStatus("FK adicionada — escolha origem e destino");
      return;
    }

    if (action === "addTrigger" && selected && selected.kind === "table") {
      const id = nextTriggerId++;
      triggers.push({
        id, name: `trg_${id}`, tableId: object.id, timing: "BEFORE", events: ["INSERT"],
        body: "", description: "",
        x: 1300 + (triggers.length % 3) * 320, y: 100 + Math.floor(triggers.length / 3) * 220
      });
      expanded.trg.add(id);
      afterModelChange({ rerenderPanel: true });
      updateStatus("Trigger adicionada");
      return;
    }

    if (action === "applyTriggerTemplate") {
      const trg = triggers.find((t) => t.id === parseInt(actionEl.dataset.trgId, 10));
      const tpl = triggerTemplateDefs.find((t) => t.key === actionEl.dataset.template);
      if (!trg || !tpl) return;
      if (!trg.name || /^trg_\d+$/.test(trg.name)) trg.name = `trg_${tpl.key}`;
      trg.timing = tpl.timing;
      trg.events = tpl.events.slice();
      trg.body = buildTemplateBody(tpl.key, trg);
      afterModelChange({ rerenderPanel: true });
      updateStatus(`Template "${tpl.name}" aplicado`);
      return;
    }

    if (action === "previewTriggerSql") {
      const trg = triggers.find((t) => t.id === parseInt(actionEl.dataset.trgId, 10));
      if (!trg) return;
      if (!trg.tableId || !tables[trg.tableId]) { updateStatus("Selecione a tabela da trigger"); return; }
      if (!(trg.events || []).length) { updateStatus("Marque pelo menos um evento"); return; }
      openSqlDialog(triggerToSQL(trg), `${dbConfig[currentDatabase].name} (preview)`);
      return;
    }

    if (action === "previewViewSql" && selected && selected.kind === "view") {
      openSqlDialog(object.toSQL(), `${dbConfig[currentDatabase].name} (preview)`);
      return;
    }

    if (action === "deleteObject" && selected) {
      deleteSelectedObject();
      return;
    }
  }

  function removePanelItem(kindKey, id) {
    const table = getSelectedObject();

    if (kindKey === "col" && selected.kind === "table") {
      if (!confirm("Remover coluna?")) return;
      const col = table.columns[id];
      if (col && col.isFK) foreignKeys = foreignKeys.filter((fk) => fk.sourceColumnId !== id);
      // So descarta os indices que CONTINHAM a coluna e ficaram vazios
      // (um indice recem-criado, ainda sem colunas, nao pode sumir junto).
      const affectedIndexIds = new Set(indexes.filter((idx) => idx.columns.includes(id)).map((idx) => idx.id));
      indexes.forEach((idx) => { idx.columns = idx.columns.filter((cid) => cid !== id); });
      indexes = indexes.filter((idx) => !(affectedIndexIds.has(idx.id) && idx.columns.length === 0));
      delete table.columns[id];
      updateStatus("Coluna removida");
    }

    if (kindKey === "idx") {
      if (!confirm("Remover indice?")) return;
      indexes = indexes.filter((i) => i.id !== id);
      updateStatus("Indice removido");
    }

    if (kindKey === "fk") {
      if (!confirm("Remover chave estrangeira?")) return;
      const fk = foreignKeys.find((f) => f.id === id);
      if (fk) {
        const sourceCol = tables[fk.sourceTableId]?.columns[fk.sourceColumnId];
        if (sourceCol) sourceCol.isFK = false;
      }
      foreignKeys = foreignKeys.filter((f) => f.id !== id);
      updateStatus("FK removida");
    }

    if (kindKey === "trg") {
      if (!confirm("Remover trigger?")) return;
      triggers = triggers.filter((t) => t.id !== id);
      updateStatus("Trigger removida");
    }

    afterModelChange({ rerenderPanel: true });
  }

  function deleteSelectedObject() {
    if (selected.kind === "table") {
      if (!confirm("Excluir tabela? FKs, indices e triggers dela tambem serao removidos.")) return;
      const id = selected.id;
      foreignKeys = foreignKeys.filter((fk) => fk.sourceTableId !== id && fk.targetTableId !== id);
      indexes = indexes.filter((idx) => idx.tableId !== id);
      triggers = triggers.filter((t) => t.tableId !== id);
      delete tables[id];
      updateStatus("Tabela removida");
    } else if (selected.kind === "view") {
      if (!confirm("Remover esta view?")) return;
      delete views[selected.id];
      updateStatus("View removida");
    } else if (selected.kind === "trigger") {
      if (!confirm("Remover trigger?")) return;
      triggers = triggers.filter((t) => t.id !== selected.id);
      updateStatus("Trigger removida");
    }
    selected = null;
    afterModelChange({ rerenderPanel: true });
  }

