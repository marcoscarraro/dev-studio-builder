  function indentBody(body) {
    return body.split("\n").map((l) => "    " + l).join("\n");
  }

  function triggerToSQL(trg) {
    const table = tables[trg.tableId];
    if (!table) return "";
    const q = getQuotes();
    const tName = `${q.start}${table.name}${q.end}`;
    const body = (trg.body || "").trim();
    const db = currentDatabase;
    let out = "";
    if (db === "mysql") {
      trg.events.forEach((evt, i) => {
        let tName2 = trg.name;
        if (trg.events.length > 1) tName2 = `${trg.name}_${evt.toLowerCase()}`;
        out += `DELIMITER $$\nCREATE TRIGGER ${q.start}${tName2}${q.end} ${trg.timing} ${evt} ON ${tName}\nFOR EACH ROW\nBEGIN\n${indentBody(body)}\nEND$$\nDELIMITER ;\n`;
        if (i < trg.events.length - 1) out += `\n`;
      });
    } else if (db === "sqlite") {
      trg.events.forEach((evt) => {
        let tName2 = trg.name;
        if (trg.events.length > 1) tName2 = `${trg.name}_${evt.toLowerCase()}`;
        out += `CREATE TRIGGER ${q.start}${tName2}${q.end} ${trg.timing} ${evt} ON ${tName}\nBEGIN\n${indentBody(body)}\nEND;\n`;
      });
    } else {
      out += `CREATE TRIGGER ${q.start}${trg.name}${q.end} ${trg.timing} ${trg.events.join(" OR ")} ON ${tName}\nBEGIN\n${indentBody(body)}\nEND;\n`;
    }
    return out;
  }

  function generateTriggersSQL() {
    if (triggers.length === 0) return "";
    let sql = `\n-- ========== TRIGGERS ==========\n\n`;
    triggers.forEach((trg) => { sql += triggerToSQL(trg) + "\n"; });
    return sql;
  }

