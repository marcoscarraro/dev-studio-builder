  function onDragMove(e) {
    if (draggingTable !== null) {
      const table = tables[draggingTable];
      if (table) { table.updatePosition(e.clientX - dragStartX, e.clientY - dragStartY); }
    } else if (draggingView !== null) {
      const view = views[draggingView];
      if (view) { view.updatePosition(e.clientX - dragStartX, e.clientY - dragStartY); }
    } else if (draggingTrigger !== null) {
      const trg = triggers.find((t) => t.id === draggingTrigger);
      if (trg) {
        trg.x = e.clientX - dragStartX;
        trg.y = e.clientY - dragStartY;
        const card = document.getElementById(`trigger-${trg.id}`);
        if (card) {
          card.style.left = `${trg.x}px`;
          card.style.top = `${trg.y}px`;
        }
      }
    }
  }

