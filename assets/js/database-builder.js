  function selectObject(kind, id, options) {
    selected = { kind, id };
    if (options && options.fromCanvas) {
      // Durante o mousedown do arraste nao se pode reconstruir o diagrama
      // (o card seria substituido no meio do evento): so troca as classes.
      document.querySelectorAll(".table-card.selected, .view-card.selected, .trigger-card.selected").forEach((el) => el.classList.remove("selected"));
      const prefix = { table: "table", view: "view", trigger: "trigger" }[kind];
      const card = document.getElementById(`${prefix}-${id}`);
      if (card) card.classList.add("selected");
    } else {
      renderDiagram();
    }
    renderTableList();
    renderProps();
  }

